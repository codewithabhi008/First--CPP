#include <iostream>

using namespace std;

int main(){

    // Basics Program in C++ 
    // endl is used to insert a new line in the output stream
    // << is the insertion operator used to send data to the output stream
    
    cout <<"Hello AT";
    cout<<endl;  
    cout <<"Hello ASH";

    // this is the same as above but in a single line

    cout <<"Hello AT" << endl<< "Hello ASH" << endl;

    return 0;
}